// Combines the two read-only extraction snapshots into data/her-sources.mjs (committed).
// Usage: python3 tools/extract-her-sources.py && node tools/extract-synthai-rule.mjs && node tools/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const raw = JSON.parse(readFileSync(new URL('./her-sources.raw.json', import.meta.url)));
const syn = JSON.parse(readFileSync(new URL('./synthai-rule.raw.json', import.meta.url)));
for (const g of raw.gates) g.synthaiRule = syn.gates[g.gate];
raw.generatedFrom.synthaiRule = syn.source;
const banner = '// GENERATED by tools/build-data.mjs from read-only copies of Alexis\'s own source material.\n' +
  '// Do not hand-edit: re-run the tools. Values are kept AS PRINTED in each source (OCR spelling included).\n';
writeFileSync(new URL('../data/her-sources.mjs', import.meta.url), banner + 'const HER_SOURCES = ' + JSON.stringify(raw, null, 1) + ';\nexport default HER_SOURCES;\n');
console.log('wrote data/her-sources.mjs');
